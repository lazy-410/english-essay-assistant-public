import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'knowledge');
const V2 = path.join(DIR, 'writing');
const required = ['sources.json','page-map.json','methods.json','skeletons.json','variants.json','examples.json','warnings.json','relations.json','aliases.json','audit.json'];
const errors = [];
const read = async (file) => JSON.parse(await readFile(path.join(file.startsWith('raw') || file.startsWith('slp') ? DIR : V2, file), 'utf8'));
const fail = (message) => errors.push(message);
const files = Object.fromEntries(await Promise.all(required.map(async (f) => [f, await read(f)])));
const rawFiles = ['raw-01-12.json','raw-13-24.json','raw-25-36.json','raw-37-47.json'];
const slpFiles = ['slp-big-e1.json','slp-big-e2.json','slp-small-e1.json','slp-small-e2.json'];
const rawDocs = await Promise.all([...rawFiles, ...slpFiles].map(read));
const sourceEntries = rawDocs.flatMap((d) => d.pages.flatMap((p) => p.entries ?? []));
const slpEntries = rawDocs.slice(4).flatMap((d) => d.pages.flatMap((p) => p.entries ?? []));
const sourceIds = new Set(sourceEntries.map((e) => e.id));
const skeletons = files['skeletons.json'].skeletons ?? [];
const variants = files['variants.json'].variants ?? [];
const examples = files['examples.json'].examples ?? [];
const methods = files['methods.json'].methods ?? [];
const pages = files['page-map.json'].pages ?? [];
const relations = files['relations.json'].relations ?? {};
if (slpEntries.length !== 158) fail(`SLP entries 应为 158，实际 ${slpEntries.length}`);
if (skeletons.length !== sourceEntries.length) fail(`skeletons 应与来源 entries 一一对应：${skeletons.length}/${sourceEntries.length}`);
if (new Set(skeletons.map((s) => s.sourceEntryId)).size !== sourceEntries.length) fail('skeleton sourceEntryId 非一一映射');
for (const id of sourceIds) if (!skeletons.some((s) => s.sourceEntryId === id)) fail(`缺少 source entry ${id}`);
for (const s of skeletons) {
  for (const key of ['rhetoricalFunction','semanticKey','conflictGroup','applicability','slots','sourceRefs','status','productionEligible','estimatedWords']) if (!(key in s)) fail(`${s.id} 缺少 ${key}`);
  if (!Array.isArray(s.applicability) || !Array.isArray(s.slots) || !Array.isArray(s.sourceRefs)) fail(`${s.id} 数组字段类型错误`);
  if (s.productionEligible !== (s.status === 'production')) fail(`${s.id} status/productionEligible 不一致`);
  for (const ref of s.sourceRefs) if (!ref.source || !ref.page) fail(`${s.id} 缺少有效 sourceRef`);
}
const ids = new Set(skeletons.map((s) => s.id));
for (const v of variants) if (!ids.has(v.skeletonId)) fail(`variant ${v.id} 悬空 skeleton ${v.skeletonId}`);
for (const e of examples) for (const id of e.skeletonIds ?? []) if (!ids.has(id)) fail(`example ${e.id} 悬空 skeleton ${id}`);
for (const [id, list] of Object.entries(relations.conflictGroups ?? {})) for (const sid of list) if (!ids.has(sid)) fail(`conflict group ${id} 悬空 ${sid}`);
const expectedNotes = rawDocs.reduce((n, d) => n + d.pages.reduce((m, p) => m + (p.pageNotes ?? []).length, 0), 0);
if (methods.length !== expectedNotes) fail(`pageNotes 未完整迁移：${methods.length}/${expectedNotes}`);
const expectedCoverage = Object.fromEntries(slpFiles.map((f, i) => [f.replace('.json',''), rawDocs[i + 4].coverage ?? { included: [], mergedAsDuplicate: [] }]));
const audit = files['audit.json'].audit;
if (JSON.stringify(audit.migration.coverage) !== JSON.stringify(expectedCoverage)) fail('coverage included/mergedAsDuplicate 未完整迁移');
if (audit.migration.rawEntryCount !== sourceEntries.length || audit.migration.slpEntryCount !== 158) fail('audit entry 计数不一致');
const mergedYears = Object.values(expectedCoverage).flatMap((c) => c.mergedAsDuplicate).map((x) => x.match(/(?<!\\d)(?:(?:19|20)\\d{2}|\\d{2})\\s*年/)?.[0]).filter(Boolean).map((x) => x.replace(/\\s*年/, '').length === 2 ? `20${x.replace(/\\s*年/, '')}` : x.replace(/\\s*年/, ''));
const restoredYears = examples.filter((e) => e.restoredFromCoverage).map((e) => e.year);
for (const year of mergedYears) if (!restoredYears.includes(year)) fail(`mergedAsDuplicate 年份 ${year} 未恢复为 example`);
const sourceRefIds = new Set(skeletons.flatMap((s) => s.sourceRefs.map((r) => r.entryId)).filter(Boolean));
for (const id of sourceIds) if (!sourceRefIds.has(id)) fail(`sourceRef 缺失 ${id}`);
if (pages.length !== rawDocs.reduce((n, d) => n + d.pages.length, 0)) fail('page-map 页数不完整');
console.log(`V2 验收：${pages.length} pages / ${methods.length} pageNotes / ${sourceEntries.length} entries（SLP ${slpEntries.length}）/ ${skeletons.length} skeletons / ${variants.length} variants / ${examples.length} examples`);
console.log(`生产骨架：${skeletons.filter((s) => s.productionEligible).length}；恢复 merged 年份：${[...new Set(restoredYears)].join(', ') || '无'}`);
if (errors.length) { console.error(`\n验收失败（${errors.length}）：\n- ${errors.join('\n- ')}`); process.exit(1); }
console.log('写作知识库 V2 验收通过。');
